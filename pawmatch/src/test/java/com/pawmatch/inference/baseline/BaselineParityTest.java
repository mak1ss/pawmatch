package com.pawmatch.inference.baseline;

import static com.pawmatch.inference.baseline.ParityJson.MAPPER;
import static com.pawmatch.inference.baseline.ParityJson.firstDifference;
import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

import com.pawmatch.recommendation.domain.BreedFeatures;
import com.pawmatch.recommendation.domain.RecommendationPolicy;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestFactory;
import tools.jackson.databind.JsonNode;

/**
 * Parity of the Java port with the Python reference {@code pawmatch-baseline-1.0.0}: every golden case generated by
 * {@code tools/baseline-parity/generate_goldens.py} must produce exactly the reference output (numbers by value).
 */
class BaselineParityTest {

    private final BaselineEngine engine = new BaselineEngine();

    @Test
    void reproducesTheMlTeamsExampleResult() throws IOException {
        JsonNode expected = ParityJson.toContract(read("/inference/baseline/example_result.json"));
        JsonNode profile = MAPPER.readTree("""
                {"activity_level": 3, "shedding_tolerance": 2, "grooming_capacity": 2, "mental_stimulation_capacity": 3,
                 "barking_tolerance": 2, "preferred_size": "Small", "has_young_children": true, "has_other_dogs": false,
                 "has_cats": false, "housing_type": "apartment", "walk_minutes_daily": 60, "alone_hours_daily": 4,
                 "owner_experience": "none", "training_minutes_daily": 20}""");

        JsonNode actual = MAPPER.valueToTree(engine.recommend(ParityJson.profile(profile), SeedCatalogue.breeds(),
                RecommendationPolicy.LIMIT, RecommendationPolicy.MIN_SCORE));

        assertThat(firstDifference(expected, actual, "$")).isNull();
    }

    @TestFactory
    Stream<DynamicTest> matchesEveryGeneratedGoldenCase() throws IOException {
        JsonNode cases = read("/inference/baseline/goldens.json").get("cases");
        assertThat(cases.size()).as("golden cases").isGreaterThan(100);
        List<DynamicTest> tests = new ArrayList<>();
        for (JsonNode golden : cases) {
            tests.add(DynamicTest.dynamicTest(golden.get("name").asString(), () -> {
                JsonNode actual = switch (golden.get("kind").asString()) {
                    case "recommend" -> MAPPER.valueToTree(engine.recommend(ParityJson.profile(golden.get("profile")),
                            SeedCatalogue.breeds(), RecommendationPolicy.LIMIT, RecommendationPolicy.MIN_SCORE));
                    case "compare" -> MAPPER.valueToTree(engine.compare(ParityJson.profile(golden.get("profile")),
                            breeds(golden.get("breed_ids"))));
                    default -> throw new IllegalArgumentException("Unknown case kind");
                };
                assertThat(firstDifference(golden.get("expected"), actual, "$")).isNull();
            }));
        }
        return tests.stream();
    }

    private static List<BreedFeatures> breeds(JsonNode ids) {
        List<BreedFeatures> breeds = new ArrayList<>();
        ids.forEach(id -> breeds.add(SeedCatalogue.breed(id.asString())));
        return breeds;
    }

    private static JsonNode read(String resource) throws IOException {
        try (InputStream in = BaselineParityTest.class.getResourceAsStream(resource)) {
            return MAPPER.readTree(in);
        }
    }
}
