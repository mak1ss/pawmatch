package com.pawmatch.recommendation.adapter.in.web;

import java.math.BigDecimal;
import java.util.List;
import java.util.UUID;
import java.util.function.Function;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.pawmatch.recommendation.adapter.in.web.RecommendationRunResponse.FactorResponse;
import com.pawmatch.recommendation.domain.BreedComparison;
import com.pawmatch.recommendation.domain.ScoringResult;

/**
 * A side-by-side assessment of the requested breeds, in the requested order. Model fields keep the model's vocabulary
 * ({@code breed_id} is the breed slug). Explanation texts are generated by the model in Ukrainian.
 * <p>
 * There is no {@code score_meaning} here: the frontend shows the "index, not a probability" disclaimer on the compare
 * screen from its own copy.
 */
record ComparisonResponse(
        UUID sessionId,
        int answersVersion,
        String modelVersion,
        String datasetVersion,
        List<ComparedBreedResponse> breeds) {

    /** @param imageUrl resolves a breed slug to its photo URL, or null when it has none */
    static ComparisonResponse from(BreedComparison comparison, Function<String, String> imageUrl) {
        return new ComparisonResponse(comparison.sessionId(), comparison.answersVersion(),
                comparison.result().modelVersion(), comparison.datasetVersion(),
                comparison.result().breeds().stream()
                        .map(breed -> ComparedBreedResponse.from(breed, imageUrl.apply(breed.breedId())))
                        .toList());
    }

    /**
     * One compared breed. An excluded breed has {@code eligible: false}, its {@code exclusion_reasons} and
     * {@code compatibility_index: null}; its factors are still returned so the per-criterion match can be shown.
     * {@code image_url} is null when the breed has no photo yet.
     */
    @JsonInclude(JsonInclude.Include.ALWAYS)
    record ComparedBreedResponse(String breedId, String breedName, String breedNameEn, boolean eligible,
                                 List<String> exclusionReasons, BigDecimal compatibilityIndex,
                                 List<FactorResponse> factors, List<String> reasons, List<String> warnings,
                                 String sourceUrl, String imageUrl) {

        static ComparedBreedResponse from(ScoringResult.ScoredBreed breed, String imageUrl) {
            return new ComparedBreedResponse(breed.breedId(), breed.breedName(), breed.breedNameEn(),
                    breed.eligible(), breed.exclusionReasons(), breed.compatibilityIndex(),
                    breed.factors().stream().map(FactorResponse::from).toList(),
                    breed.reasons(), breed.warnings(), breed.sourceUrl(), imageUrl);
        }
    }
}
